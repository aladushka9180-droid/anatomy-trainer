assert.doesNotMatch(forward,/perform public\.sell_minuta_commercial_product_v151/);
assert.doesNotMatch(forward,/update public\.(organization_finance_settings|organization_inventory_settings|organization_benefit_settings)/);
assert.doesNotMatch(forward,/insert into public\.inventory_stock_balances/);
