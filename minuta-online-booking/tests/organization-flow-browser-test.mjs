import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { fixture } from './organization-flow-fixture.mjs';
const { chromium } = await import(process.env.MINUTA_PLAYWRIGHT_MODULE ? pathToFileURL(process.env.MINUTA_PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) });
const output = process.env.MINUTA_ORG_FLOW_SCREENSHOTS;
if (output) mkdirSync(output, { recursive: true });
let checks = 0;
const errors = [];
try {
  for (const theme of ['pink-porcelain', 'celadon', 'oled-mono']) for (const width of [390, 760, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, serviceWorkers: 'block', reducedMotion: 'reduce' });
    page.on('pageerror', error => errors.push(error.message));
    await fixture(page, { theme });
    assert.equal(await page.locator('.of-count').innerText(), '0 из 4'); checks++;
    assert.match(await page.locator('.of-booking-note').innerText(), /самостоятельное включение пока недоступно/); checks++;
    await page.locator('[data-org-action="select"][data-org-index="2"]').click();
    assert.equal(await page.locator('.of-step.is-active').getAttribute('data-org-step'), '2'); checks++;
    await page.evaluate(() => flow.load());
    assert.equal(await page.evaluate(() => document.activeElement.dataset.orgIndex), '2'); checks++;
    await page.locator('[data-org-action="rename"]').click();
    assert.notEqual(await page.locator('#organizationForm button[type="submit"]').evaluate(node => getComputedStyle(node).backgroundColor), 'rgba(0, 0, 0, 0)'); checks++;
    await page.locator('#organizationName').fill('Новое название');
    await page.evaluate(() => { renameFailure = true; renamePending = true; });
    await page.locator('#organizationForm button[type="submit"]').click();
    await page.waitForFunction(() => Boolean(window.resolveRename));
    assert.equal(await page.locator('#organizationForm button[type="submit"]').isEnabled(), false); checks++;
    await page.evaluate(() => { resolveRename(); renamePending = false; });
    await page.locator('#organizationError').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#organizationName').inputValue(), 'Новое название'); checks++;
    assert.equal(await page.locator('.of-count').innerText(), '0 из 4'); checks++;
    if (output && theme === 'pink-porcelain') await page.screenshot({ path: join(output, `rename-error-${width}.png`), fullPage: true });
    await page.evaluate(() => { renameFailure = false; });
    await page.locator('#organizationForm button[type="submit"]').click();
    await page.locator('#organizationForm').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#organizationTitle').innerText(), 'Новое название'); checks++;
    await page.evaluate(async () => {
      orgData.locations = [{ id: 'l1', name: 'Центр', address: 'Тестовый адрес', active: true }];
      orgData.members = [{ user_id: 'test-user', display_name: 'Анна', active: true, is_bookable: true, role: 'owner' }];
      shiftData.services = [{ id: 's1', performer_id: 'test-user', name: 'Массаж', duration_minutes: 60 }];
      shiftData.shifts = [{ performer_id: 'test-user', location_id: 'l1', shift_date: '2026-10-02', start_time: '10:00', end_time: '18:00', active: true }];
      await orgController.load(); await flow.load();
    });
    assert.equal(await page.locator('.of-count').innerText(), '4 из 4'); checks++;
    // A confirmed checklist never modifies the separate public-booking flag.
    assert.equal(await page.evaluate(() => orgData.public_booking_enabled), false); checks++;
    await page.locator('[data-org-action="manage"]').click();
    assert.equal(await page.locator('.of-steps').isVisible(), true); checks++;
    await page.locator('[data-org-action="manage"]').click();
    assert.equal(await page.locator('.of-steps').isVisible(), false); checks++;
    if (output) await page.screenshot({ path: join(output, `ready-${theme}-${width}.png`), fullPage: true });
    await page.evaluate(async () => { readFailure = true; await flow.load(); });
    assert.equal(await page.locator('.of-count').innerText(), '2 из 4 · проверка неполная'); checks++;
    assert.equal(await page.locator('.of-ready').isVisible(), false); checks++;
    await page.evaluate(() => { readFailure = false; });
    await page.locator('[data-org-action="retry"]').click();
    await page.waitForFunction(() => document.querySelector('.of-count').textContent === '4 из 4'); checks++;
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${theme}/${width} overflow`); checks++;
    await page.locator('[data-org-action="manage"]').click();
    await page.locator('[data-org-action="select"][data-org-index="0"]').click();
    await page.locator('[data-org-action="open"]').click();
    assert.equal(await page.locator('[data-location-card="l1"]').getAttribute('open'), ''); checks++;
    assert.equal(await page.locator('[data-location-card="l1"] input[name="address"]').inputValue(), 'Тестовый адрес'); checks++;
    assert.equal(await page.evaluate(() => calls.filter(item => item.name === 'update_minuta_organization').length), 2); checks++;
    await page.close();
  }
  const page = await browser.newPage({ viewport: { width: 390, height: 1000 }, serviceWorkers: 'block' });
  page.on('pageerror', error => errors.push(error.message));
  await fixture(page, { ready: true, role: 'specialist' });
  assert.equal(await page.locator('[data-org-action="rename"]').isVisible(), false); checks++;
  assert.equal(await page.locator('.of-count').innerText(), '2 из 4 · проверка неполная'); checks++;
  await page.evaluate(async () => { shiftData.organization_id = 'foreign-org'; await flow.load(); });
  assert.equal(await page.locator('.of-ready').isVisible(), false); checks++;
  assert.equal(await page.evaluate(() => calls.every(item => item.name.startsWith('get_'))), true); checks++;
  await page.evaluate(async () => { shiftPending = true; void flow.load(); });
  await page.waitForFunction(() => Boolean(window.resolveShift));
  await page.evaluate(() => { generation++; flow.reset(); resolveShift(); });
  assert.equal(await page.evaluate(() => orgData.public_booking_enabled), false); checks++;
  await page.close();
  const edge = await browser.newPage({ viewport: { width: 390, height: 1000 }, serviceWorkers: 'block', reducedMotion: 'reduce' });
  await fixture(edge, { ready: true });
  const truth = await edge.evaluate(() => {
    const count = (org, data) => MinutaOrganizationFlow.configuration(org, data, 'ready', '2026-10-02', '2026-10-15').filter(item => item.done === true).length;
    const variants = [];
    let org = structuredClone(orgData), data = structuredClone(shiftData); data.shifts[0].end_time = '24:00:00'; variants.push(count(org, data));
    org = structuredClone(orgData); data = structuredClone(shiftData); org.members[0].active = false; variants.push(count(org, data));
    org = structuredClone(orgData); data = structuredClone(shiftData); org.locations[0].address = ''; variants.push(count(org, data));
    org = structuredClone(orgData); data = structuredClone(shiftData); data.shifts[0].shift_date = '2026-10-01'; variants.push(count(org, data));
    org = structuredClone(orgData); data = structuredClone(shiftData); data.absences = [{ performer_id: 'test-user', active: true, starts_on: '2026-10-02', ends_on: '2026-10-03' }]; variants.push(count(org, data));
    org = structuredClone(orgData); data = structuredClone(shiftData); org.members.push({ user_id: 'second', active: true, is_bookable: true }); variants.push(count(org, data));
    return variants;
  });
  assert.deepEqual(truth, [4, 1, 2, 3, 3, 2]); checks += truth.length;
  await edge.locator('[data-org-action="rename"]').click();
  await edge.locator('#organizationName').fill('Первое имя');
  await edge.evaluate(() => { renamePending = true; });
  await edge.locator('#organizationForm button[type="submit"]').click();
  await edge.waitForFunction(() => Boolean(window.resolveRename));
  await edge.locator('#organizationName').fill('Следующий черновик');
  await edge.evaluate(() => { resolveRename(); });
  await edge.waitForFunction(() => document.getElementById('organizationTitle').textContent === 'Первое имя');
  assert.equal(await edge.locator('#organizationName').inputValue(), 'Следующий черновик'); checks++;
  assert.equal(await edge.locator('#organizationForm').isVisible(), true); checks++;
  await edge.close();
  assert.deepEqual(errors, []);
  console.log(`Organization flow: ${checks} browser checks PASS; 3 themes × 390/760/1440; all networking intercepted; synthetic rename only.`);
} finally { await browser.close(); }
