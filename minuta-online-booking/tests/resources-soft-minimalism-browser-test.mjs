import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { buildResourceFixture } from './resources-soft-minimalism-fixture.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const fixture = buildResourceFixture();
const folder = dirname(fixture);
const server = createServer((req,res) => {
  const name = new URL(req.url,'http://localhost').pathname.split('/').pop() || 'fixture.html';
  if (!['fixture.html','ui-icons.svg','resource-icons.svg','resources-soft-minimalism.css'].includes(name)) { res.writeHead(404); res.end(); return; }
  res.setHeader('Content-Type',name.endsWith('.svg')?'image/svg+xml':name.endsWith('.css')?'text/css':'text/html');
  res.end(readFileSync(resolve(folder,name)));
});
await new Promise(done=>server.listen(0,'127.0.0.1',done));
const base = 'http://127.0.0.1:' + server.address().port;
const browser = await chromium.launch({headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const page = await context.newPage();
const checks = [], errors = [];
page.on('pageerror',error=>errors.push(error.message));
await context.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
const check = (label,condition) => { assert.ok(condition,label); checks.push(label); };
const open = async(query='') => { await page.goto(base+'/fixture.html'+query); await page.locator('body[data-ready=true]').waitFor(); };
const card = id => page.locator('[data-resource-card="'+id+'"]');
const count = () => page.locator('#resourcesList [data-resource-card]').count();
try {
  await open();
  check('12 resources initially, total includes inactive',await count()===12 && await page.locator('#resourcesCount').textContent()==='26');
  check('Groups hidden until requested',!await page.locator('#resourceGroupsSection').isVisible());
  check('Untrusted names rendered as text',await card('res-1').locator('strong').textContent()==='Кабинет 01 <тест>');
  await page.locator('#resourceListGroup').selectOption('grp-table');
  check('Group filter and massage-table icon',await count()===5 && (await page.locator('#resourcesList use').first().getAttribute('href')).endsWith('#table'));
  await page.locator('#resourceListLocation').selectOption('loc-1');
  check('Combined filters show an honest empty state',await count()===0 && await page.getByText('Ничего не найдено',{exact:true}).isVisible());
  await page.locator('#resourceListReset').click();
  await page.locator('#resourceListStatus').selectOption('inactive');
  check('Inactive filter includes both branches/groups',await count()===2);
  await page.locator('#resourceListSearch').fill('  КАБИНЕТ 11 ');
  check('Search trims and ignores case',await count()===1);
  await page.locator('#resourceListReset').click();
  await card('res-1').locator('summary').click();
  await card('res-1').locator('input[name=name]').fill('Черновик');
  await page.locator('#resourceListMore').click();
  check('Show more preserves an open editor and unsaved value',await count()===24 && await card('res-1').getAttribute('open')!==null && await card('res-1').locator('input[name=name]').inputValue()==='Черновик');
  await card('res-20').locator('summary').click();
  await card('res-20').locator('input[name=name]').fill('Черновик скрытого ресурса');
  await page.locator('#resourceListCollapse').click();
  check('Collapse returns to 12 visible resources',await page.locator('#resourcesList .resource-item:visible').count()===12 && !await page.locator('#resourceListCollapse').isVisible() && await page.locator('#resourceListMore').isVisible());
  await page.locator('#resourceListMore').click();
  check('Expanding again restores the hidden editor and its draft',await card('res-20').getAttribute('open')!==null && await card('res-20').locator('input[name=name]').inputValue()==='Черновик скрытого ресурса');
  await card('res-20').getByRole('button',{name:'Отмена',exact:true}).click();
  await card('res-1').getByRole('button',{name:'Отмена',exact:true}).click();
  await card('res-1').locator('summary').click();
  check('Cancel restores the last server value',await card('res-1').locator('input[name=name]').inputValue()==='Кабинет 01 <тест>');
  await card('res-1').locator('input[name=name]').press('Escape');
  check('Escape closes editor and returns keyboard focus',await card('res-1').getAttribute('open')===null && await card('res-1').locator('summary').evaluate(e=>e===document.activeElement));
  await page.locator('#resourceMainAction').click();
  check('Main action opens real form and focuses its name',await page.locator('#resourceCreator').getAttribute('open')!==null && await page.locator('#resourceName').evaluate(e=>e===document.activeElement));
  await page.locator('#resourceName').fill('Новый стол');
  await page.locator('#resourceLocation').selectOption('loc-2');
  await page.locator('#resourceGroup').selectOption('grp-table');
  await page.locator('#resourceForm').getByRole('button',{name:'Создать ресурс',exact:true}).click();
  await page.getByText('Ресурс создан',{exact:true}).waitFor();
  check('Create uses existing RPC and closes the form',await page.locator('#resourcesCount').textContent()==='27' && await page.locator('#resourceCreator').getAttribute('open')===null && await page.evaluate(()=>fixtureCalls.some(c=>c.name==='create_minuta_resource'&&c.args.p_group==='grp-table'&&c.args.p_location==='loc-2')));
  await page.locator('#resourceListSearch').fill('Новый стол');
  const created=page.locator('#resourcesList [data-resource-card]');
  await created.locator('summary').click();
  await created.locator('input[name=name]').fill('Стол на Садовой');
  await created.locator('input[name=active]').uncheck();
  await created.getByRole('button',{name:'Сохранить ресурс',exact:true}).click();
  await page.getByText('Ресурс сохранён',{exact:true}).waitFor();
  await page.locator('#resourceListSearch').fill('Стол на Садовой');
  check('Edit saves name and active flag on the server contract',await count()===1 && (await page.locator('#resourcesList').textContent()).includes('Отключён'));
  await page.locator('#fixtureFailure').selectOption('resource_has_future_bookings');
  await page.locator('#resourcesList summary').click();
  await page.locator('#resourcesList input[name=name]').fill('Не должно сохраниться');
  await page.locator('#resourcesList').getByRole('button',{name:'Сохранить ресурс',exact:true}).click();
  await page.locator('[data-resource-error]:visible').waitFor();
  check('Future bookings error remains visible and the saved name unchanged',(await page.locator('[data-resource-error]:visible').textContent()).includes('будущие записи') && (await page.locator('#resourcesList strong').textContent())==='Стол на Садовой');
  await page.locator('#resourceListReset').click();
  await page.locator('#resourceGroupsToggle').click();
  await page.locator('[data-resource-group-card="grp-room"] summary').click();
  await page.locator('[data-resource-group-card="grp-room"] input[name=name]').fill('Недопустимое изменение');
  await page.locator('[data-resource-group-card="grp-room"]').getByRole('button',{name:'Сохранить группу',exact:true}).click();
  await page.locator('[data-resource-group-error]:visible').waitFor();
  check('Group failure reopens group manager and focuses the error',await page.locator('#resourceGroupsSection').isVisible() && await page.locator('[data-resource-group-error]:visible').evaluate(e=>e===document.activeElement));
  await page.locator('#fixtureFailure').selectOption('');
  await page.locator('[data-resource-group-card="grp-room"] input[name=name]').fill('Кабинеты центра');
  await page.locator('[data-resource-group-card="grp-room"]').getByRole('button',{name:'Сохранить группу',exact:true}).click();
  await page.getByText('Группа сохранена',{exact:true}).waitFor();
  check('Group edit refreshes names in resource metadata',(await card('res-1').textContent()).includes('Кабинеты центра'));
  await page.locator('#resourceRequirementsDisclosure > summary').click();
  await page.locator('[data-requirement-group="grp-table"]').fill('2');
  await page.locator('#resourceRequirementSubmit').click();
  await page.getByText('Требования услуги сохранены',{exact:true}).waitFor();
  check('Service requirements retain the existing RPC contract',await page.evaluate(()=>fixtureCalls.some(c=>c.name==='replace_minuta_service_resource_requirements'&&c.args.p_requirements.some(r=>r.group_id==='grp-table'&&r.quantity===2))));
  await page.locator('#resourceAuditPanel summary').click();
  check('Audit remains accessible',await page.locator('#resourceAuditList').isVisible());
  await open('?mode=readonly');
  check('Read-only role has no editable resources or main action',!await page.locator('#resourceMainAction').isVisible() && await count()===0 && await page.locator('#resourcesList article').count()===12);
  await page.locator('#resourceGroupsToggle').click();
  check('Read-only role may inspect groups without forms',await page.locator('#resourceGroupsList article').count()===4 && await page.locator('#resourceGroupsList form').count()===0);
  await open('?mode=empty');
  check('Empty state starts with group setup',await page.locator('#resourceMainActionLabel').textContent()==='Создать группу' && await page.locator('#resourceGroupsSection').isVisible() && !await page.locator('#resourceListFilters').isVisible());
  await page.locator('#resourceMainAction').click();
  await page.locator('#resourceGroupName').fill('Новая группа');
  await page.locator('#resourceGroupKind').selectOption('table');
  await page.locator('#resourceGroupForm').getByRole('button',{name:'Создать группу',exact:true}).click();
  await page.getByText('Группа ресурсов создана',{exact:true}).waitFor();
  check('First group advances to first resource',await page.locator('#resourceMainActionLabel').textContent()==='Добавить ресурс' && await page.locator('#resourceMainAction').isEnabled());
  await page.locator('#resourceMainAction').click();
  await page.locator('#resourceName').fill('Повторное название');
  await page.locator('#fixtureFailure').selectOption('duplicate key');
  await page.locator('#resourceForm').getByRole('button',{name:'Создать ресурс',exact:true}).click();
  await page.locator('#resourceError:visible').waitFor();
  check('Duplicate create reports an error without a new resource',(await page.locator('#resourceError').textContent()).includes('уже используется') && !await page.locator('#resourcesCount').isVisible());
  await page.locator('#fixtureFailure').selectOption('network');
  await page.locator('#resourceForm').getByRole('button',{name:'Создать ресурс',exact:true}).click();
  await page.locator('#resourceError:visible').waitFor();
  check('Network failure keeps form visible and retry enabled',(await page.locator('#resourceError').textContent()).includes('не сохранено') && await page.locator('#resourceCreator').getAttribute('open')!==null && await page.locator('#resourceForm button[type=submit]').isEnabled());
  await open('?mode=no-location');
  check('Missing branch keeps the existing branch setup action',await page.locator('#resourceLocationLink').isVisible());
  const layouts=[];
  for(const theme of ['pink-porcelain','noir']) {
    for(const width of [390,760,1440]) {
      await page.setViewportSize({width,height:1000});
      await open('?theme='+theme);
      if(width===390) {
        check('Mobile extra filters initially collapsed: '+theme,!await page.locator('#resourceExtraFilters').isVisible());
        await page.locator('#resourceFiltersToggle').click();
        check('Mobile filter toggle exposes real selects: '+theme,await page.locator('#resourceExtraFilters').isVisible() && await page.locator('#resourceFiltersToggle').getAttribute('aria-expanded')==='true');
        await page.locator('#resourceFiltersToggle').click();
      }
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
      check('No horizontal overflow: '+theme+' '+width,!overflow);
      let contrast;
      if(width===1440) {
        contrast=await page.evaluate(()=>{
          const canvas=document.createElement('canvas');canvas.width=canvas.height=1;const ctx=canvas.getContext('2d');
          const rgb=css=>{ctx.clearRect(0,0,1,1);ctx.fillStyle=css;ctx.fillRect(0,0,1,1);return [...ctx.getImageData(0,0,1,1).data].slice(0,3)};
          const luminance=rgb=>rgb.map(n=>{n/=255;return n<=.04045?n/12.92:((n+.055)/1.055)**2.4}).reduce((sum,n,i)=>sum+n*[.2126,.7152,.0722][i],0);
          const ratio=(a,b)=>{const x=luminance(rgb(a)),y=luminance(rgb(b));return(Math.max(x,y)+.05)/(Math.min(x,y)+.05)};
          const base=getComputedStyle(document.querySelector('#resourcesPanel')).backgroundColor;
          const text=[...document.querySelectorAll('#resourceMainAction,#resourcesList summary strong,#resourcesList summary small,#resourcesList .organization-status,#resourceListMatchCount,#resourceListSearch')].map(e=>{const cs=getComputedStyle(e);return ratio(cs.color,cs.backgroundColor==='rgba(0, 0, 0, 0)'?base:cs.backgroundColor)});
          const field=getComputedStyle(document.querySelector('#resourceListSearch'));
          return {text:Math.min(...text),field:ratio(field.borderColor,field.backgroundColor)};
        });
        check('Readable text contrast: '+theme,contrast.text>=4.5);
        check('Visible field boundary contrast: '+theme,contrast.field>=3);
      }
      await page.screenshot({path:resolve(folder,'resources-'+theme+'-'+width+'.png'),fullPage:true});
      await page.locator('#resourceMainAction').click();
      check('Create form fits: '+theme+' '+width,!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1));
      await page.locator('#resourceForm [data-resource-cancel]').click();
      await card('res-1').locator('summary').click();
      check('Editor fits: '+theme+' '+width,!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1));
      layouts.push({theme,width,overflow,...(contrast ? {contrast} : {})});
    }
  }
  check('No browser script errors',errors.length===0);
  writeFileSync(resolve(folder,'browser-results.json'),JSON.stringify({passed:checks.length,checks,layouts,errors},null,2));
  console.log('PASS '+checks.length+' resource UI checks; '+layouts.length+' responsive/theme cases; network isolated.');
} finally {
  await browser.close();
  await new Promise(done=>server.close(done));
}
