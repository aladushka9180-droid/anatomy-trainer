import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const source = await readFile(new URL('../provider-service-offers.js', import.meta.url), 'utf8');
const window = {};
vm.runInNewContext(source, { window, Intl });
const { validateOffer, previewPrice, isEligibleService, isEligibleAddonService } = window.MinutaServiceOffers;
const ids = ['10000000-0000-0000-0000-000000000001','10000000-0000-0000-0000-000000000002','10000000-0000-0000-0000-000000000003'];
const services = ids.map((id, index) => ({ id, active:true, duration_minutes:index === 2 ? 1 : 30, price_rub:500 }));
const offer = { id:null, primary_service_ids:[ids[0]], addon_service_id:ids[1], benefit_text:'Снимет напряжение в шее', discount_kind:'none', discount_value:0, additional_minutes:30, enabled:true, revision:0, priority:50 };
assert.equal(validateOffer(offer, services), '');
assert.equal(validateOffer({ ...offer, additional_minutes:0 }, services), '');
for (const additional_minutes of [-1, 481, 1.5, NaN]) assert.ok(validateOffer({ ...offer, additional_minutes }, services));
assert.equal(isEligibleService(services[2]), false);
assert.equal(isEligibleAddonService(services[2]), true);
assert.equal(isEligibleService({ ...services[0], active:false }), false);
assert.ok(validateOffer({ ...offer, addon_service_id:ids[2] }, services));
const minuteOffer = { ...offer, addon_service_id:ids[2], addon_price_rub:600, additional_minutes:0 };
assert.equal(validateOffer(minuteOffer,services),'');
assert.equal(validateOffer({ ...minuteOffer,addon_price_rub:0 },services),'');
assert.equal(validateOffer({ ...minuteOffer,addon_price_rub:1000000,additional_minutes:480 },services),'');
for(const addon_price_rub of [undefined,null,-1,1.5,1000001,NaN,'600']) assert.ok(validateOffer({ ...minuteOffer,addon_price_rub },services));
assert.equal(validateOffer({ ...minuteOffer,discount_kind:'rubles',discount_value:600 },services),'');
assert.ok(validateOffer({ ...minuteOffer,discount_kind:'rubles',discount_value:601 },services));
assert.equal(validateOffer({ ...minuteOffer,discount_kind:'rubles',discount_value:550 },services),'','Actual addon price replaces minute tariff as discount bound');
assert.ok(validateOffer({ ...minuteOffer,primary_service_ids:[ids[2]] },services),'Primary per-minute flow remains excluded');
assert.equal(validateOffer({ ...offer,addon_price_rub:null },services),'','Old fixed row nullable price compatible');
assert.ok(validateOffer({ ...offer,addon_price_rub:500 },services),'Fixed catalog service cannot silently override price');
assert.ok(validateOffer({ ...offer, primary_service_ids:[ids[2]] }, services));
assert.ok(validateOffer({ ...offer, primary_service_ids:[ids[1]] }, services));
assert.ok(validateOffer({ ...offer, primary_service_ids:[ids[0],ids[0]] }, services));
assert.ok(validateOffer({ ...offer, benefit_text:' ' }, services));
assert.ok(validateOffer({ ...offer, benefit_text:'x'.repeat(161) }, services));
for (const [discount_kind, discount_value] of [['none',1],['percent',101],['rubles',501],['rubles',-1],['rubles',1.5],['percent',NaN],['invalid',0]]) assert.ok(validateOffer({ ...offer, discount_kind, discount_value }, services));
assert.equal(previewPrice(500, 'none', 0), 500);
assert.equal(previewPrice(500, 'percent', 10), 450);
assert.equal(previewPrice(500, 'rubles', 175), 325);
assert.equal(previewPrice(501, 'percent', 12.5), 438);
assert.equal(previewPrice(501, 'percent', 50), 251);
const existing = [1,2,3].map(index => ({ ...offer, id:`20000000-0000-0000-0000-00000000000${index}` }));
assert.ok(validateOffer(offer, services, existing));
assert.equal(validateOffer({ ...offer, enabled:false }, services, existing), '');
assert.equal(validateOffer({ ...existing[0], revision:1 }, services, [existing[0]]), '');
assert.ok(validateOffer(offer, services, [existing[0]]), 'Duplicate enabled addon for same primary must reject');
assert.equal(validateOffer(offer, services, [{ ...existing[0], enabled:false }]), '');
const manyPrimaries = Array.from({length:51}, (_,index) => `30000000-0000-0000-0000-${String(index).padStart(12,'0')}`);
const manyServices = [...services,...manyPrimaries.map(id => ({id,active:true,duration_minutes:30,price_rub:100}))];
assert.ok(validateOffer({ ...offer,primary_service_ids:manyPrimaries },manyServices));
assert.equal(validateOffer({ ...offer,primary_service_ids:manyPrimaries.slice(0,50) },manyServices),'');
const archived = { ...existing[0], revision:2, addon_service_id:ids[2], primary_service_ids:['deadbeef-0000-0000-0000-000000000000'] };
assert.equal(validateOffer({ ...archived, enabled:false }, [], [archived]), '');
assert.ok(validateOffer({ ...archived, enabled:false }, [], []), 'Unknown offer cannot use disable lifecycle');
assert.equal(validateOffer({ ...archived,addon_price_rub:600,enabled:false },[],[archived]),'');
assert.doesNotMatch(source, /localStorage|sessionStorage|\.from\(['"]services['"]\).*update/);
assert.equal(services[1].price_rub, 500);
console.log('Pro service-offers contract: explicit whole-addon price including zero, catalog-price compatibility, actual-time bounds, fixed primary, max3 PASS');
