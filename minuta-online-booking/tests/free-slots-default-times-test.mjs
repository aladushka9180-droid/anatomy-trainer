import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../free-slots-share.js',import.meta.url),'utf8');
const context=vm.createContext({window:{}});
vm.runInContext(source.replace('window.MinutaFreeSlots = { createController, calculateFreeWindows }','window.MinutaFreeSlots = { createController, calculateFreeWindows, defaultPublicationTimes, buildPublication }'),context);
const {defaultPublicationTimes:select,buildPublication:build}=context.window.MinutaFreeSlots;
const clock=minutes=>String(Math.floor(minutes/60)).padStart(2,'0')+':'+String(minutes%60).padStart(2,'0');
const full=Array.from({length:109},(_,i)=>clock(600+i*5));
assert.deepEqual(Array.from(select(full)),Array.from({length:10},(_,i)=>clock(600+i*60)));
assert.deepEqual(Array.from(select(['10:30','11:30','12:30'])),['10:30','11:30','12:30']);
const gap=full.filter(time=>time<'12:00'||time>='14:20');
const gapSelection=Array.from(select(gap));
assert.deepEqual(gapSelection,['10:00','11:00','14:20','15:00','16:00','17:00','18:00','19:00']);
assert.ok(gapSelection.every(time=>gap.includes(time)),'Never invent starts rejected by server');
assert.deepEqual(Array.from(select([])),[]);
assert.deepEqual(Array.from(select(['19:00','10:00','10:00'])),['10:00','19:00']);
const text=build('2026-09-06','2026-09-06',{bookingUrl:'https://example.test',serviceLabel:'Массаж'},select(full).map(time=>({booking_date:'2026-09-06',booking_time:time})));
assert.ok(text.includes('10:00, 11:00, 12:00, 13:00, 14:00, 15:00, 16:00, 17:00, 18:00, 19:00'));
assert.ok(!text.includes('14:30'));
const slots=Array.from({length:15},(_,i)=>({booking_date:'2026-09-'+String(i+1).padStart(2,'0'),booking_time:'10:00'}));
assert.equal((build('2026-09-01','2026-09-15',{bookingUrl:'https://example.test'},slots).match(/10:00/g)||[]).length,15,'Range must not stop after seven days');
console.log('PASS: all available hourly starts, non-hour windows, busy gaps, exact server subset, full date range');
