import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const sandbox = { window:{} };
vm.runInNewContext(readFileSync(new URL('service-presets-catalog.js', root), 'utf8'), sandbox);
export const catalog = sandbox.window.MinutaServicePresetCatalog;
const quote = value => typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const professions = catalog.professions.map((p, i) => [2, 'ru-RU', p.id, p.label, p.shortLabel, i]);
const presets = catalog.professions.flatMap(p => p.services.map(s => [2, 'ru-RU', s.id, p.id, s.name, s.category, s.defaultDuration, s.rank]));
const seeds = [
  ['minuta_professions_v160', 'catalog_version,locale,profession_id,label,short_label,sort_order', professions],
  ['minuta_service_presets_v160', 'catalog_version,locale,preset_id,profession_id,name,category,default_duration_minutes,sort_order', presets]
];
const original = readFileSync(new URL('supabase-migration-v160.sql', root), 'utf8').replaceAll('\r\n', '\n');
const originalBody = original.match(/create function public\.create_provider_services_from_presets_v160\([\s\S]*? as \$\$([\s\S]*?)\$\$;/)[1];
const deletion = 'where choice.performer_id=v_uid and not (choice.profession_id=any(v_professions));';
const safeDeletion = `where choice.performer_id=v_uid and not (choice.profession_id=any(v_professions))
    and exists(select 1 from public.minuta_professions_v160 known
      where known.catalog_version=p_catalog_version and known.locale=v_locale
        and known.profession_id=choice.profession_id);`;
const resultSelection = "'profession_ids',to_jsonb(v_professions),'created_count',v_created,";
const safeResult = `'profession_ids',(select coalesce(jsonb_agg(choice.profession_id order by choice.profession_id),'[]'::jsonb)
      from public.minuta_performer_professions_v160 choice where choice.performer_id=v_uid),'created_count',v_created,`;
export const compatibleBody = originalBody.replace(deletion, safeDeletion).replace(resultSelection, safeResult);
const hash = text => createHash('md5').update(text).digest('hex');
const patchFunction = (reverse = false) => `do $guard$ declare
  target oid := 'public.create_provider_services_from_presets_v160(uuid,integer,text[],jsonb)'::regprocedure;
  body_hash text;
  definition text;
begin
  select md5(replace(prosrc,E'\\r\\n',E'\\n')) into body_hash from pg_proc where oid=target;
  if body_hash='${hash(reverse ? originalBody : compatibleBody)}' then return; end if;
  if body_hash<>'${hash(reverse ? compatibleBody : originalBody)}' then
    raise exception 'service_catalog_rpc_definition_changed';
  end if;
  definition := replace(pg_get_functiondef(target),E'\\r\\n',E'\\n');
  definition := replace(definition,$old$${reverse ? safeDeletion : deletion}$old$,$new$${reverse ? deletion : safeDeletion}$new$);
  definition := replace(definition,$old$${reverse ? safeResult : resultSelection}$old$,$new$${reverse ? resultSelection : safeResult}$new$);
  execute definition;
end $guard$;`;
export const migration = `-- Generated by scripts/build-service-catalog-v2.mjs --write. Review and release via the Pro SQL owner.
-- Adds catalog v2 and preserves choices unknown to an older client. No permission changes.
begin;
set local lock_timeout='5s';
do $$ begin
  if to_regprocedure('public.create_provider_services_from_presets_v160(uuid,integer,text[],jsonb)') is null then
    raise exception 'service_catalog_v160_required';
  end if;
end $$;
lock table public.minuta_professions_v160, public.minuta_service_presets_v160 in share row exclusive mode;
${patchFunction()}
${seeds.map(([table, columns, rows], i) => `
create temporary table catalog_v2_seed_${i} on commit drop as select ${columns} from public.${table} with no data;
insert into catalog_v2_seed_${i} values
${rows.map(row => `  (${row.map(quote).join(',')})`).join(',\n')};
-- A different existing version 2 is a collision, never an instruction to overwrite it.
do $$ begin
  if exists (select ${columns} from public.${table} where catalog_version=2
    except select ${columns} from catalog_v2_seed_${i}) then
    raise exception 'service_catalog_v2_collision';
  end if;
end $$;
insert into public.${table} (${columns},active)
select ${columns},true from catalog_v2_seed_${i}
on conflict (catalog_version,locale,${i ? 'preset_id' : 'profession_id'}) do update set active=true;
`).join('')}
commit;
`;
export const compatibilityRollback = `-- Optional full RPC rollback. First roll back catalog/UI; never erase choices to satisfy this guard.
begin;
set local lock_timeout='5s';
lock table public.minuta_performer_professions_v160 in share row exclusive mode;
do $$ begin
  if exists(select 1 from public.minuta_performer_professions_v160 choice
    where not exists(select 1 from public.minuta_professions_v160 known
      where known.catalog_version=1 and known.locale=choice.locale and known.profession_id=choice.profession_id)) then
    raise exception 'service_catalog_compatibility_still_required';
  end if;
end $$;
${patchFunction(true)}
commit;
`;
if (process.argv.includes('--write')) {
  writeFileSync(new URL('supabase-service-catalog-v2.sql', root), migration);
  writeFileSync(new URL('supabase-service-catalog-v2-compatibility-rollback.sql', root), compatibilityRollback);
}
